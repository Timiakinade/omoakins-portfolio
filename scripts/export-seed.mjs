// One-off: turn the content files in src/content into SQL that loads them into Supabase.
// Usage: node scripts/export-seed.mjs <admin-email> > supabase/seed.sql
import { readFileSync, readdirSync } from "node:fs";
import { basename, join } from "node:path";
import { parse } from "yaml";

const email = process.argv[2]?.toLowerCase();
if (!email || !email.includes("@")) {
  console.error("Usage: node scripts/export-seed.mjs <admin-email>");
  process.exit(1);
}

const dir = "src/content";
const rows = [];
const add = (type, slug, data) => {
  const { draft = false, ...rest } = data;
  rows.push({ type, slug, data: rest, live: !draft });
};

for (const f of readdirSync(join(dir, "projects"))) {
  add("project", basename(f, ".json"), JSON.parse(readFileSync(join(dir, "projects", f), "utf8")));
}
for (const f of readdirSync(join(dir, "pages"))) {
  add("page", basename(f, ".json"), JSON.parse(readFileSync(join(dir, "pages", f), "utf8")));
}
for (const f of readdirSync(join(dir, "posts"))) {
  const src = readFileSync(join(dir, "posts", f), "utf8");
  const [, front, body] = src.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const meta = parse(front);
  meta.date = new Date(meta.date).toISOString().slice(0, 10);
  add("post", basename(f, ".md"), { ...meta, body: body.trim() });
}
for (const { id, ...t } of JSON.parse(readFileSync(join(dir, "testimonials.json"), "utf8"))) {
  add("testimonial", id, t);
}
add("settings", "site", JSON.parse(readFileSync(join(dir, "site.json"), "utf8")));

const json = (v) => `$json$${JSON.stringify(v)}$json$::jsonb`;
const lit = (s) => `'${s.replace(/'/g, "''")}'`;

console.log(`-- Generated by scripts/export-seed.mjs. Loads the current site content and the admin login.
insert into public.admins (email) values (${lit(email)}) on conflict do nothing;

insert into public.entries (type, slug, draft, published, published_at) values
${rows
  .map((r) => `  (${lit(r.type)}, ${lit(r.slug)}, ${json(r.data)}, ${r.live ? json(r.data) : "null"}, ${r.live ? "now()" : "null"})`)
  .join(",\n")}
on conflict (type, slug) do nothing;`);
